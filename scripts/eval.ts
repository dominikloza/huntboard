/**
 * `pnpm eval`: runs every case in evals/extract against the configured model (AI_PROVIDER from
 * .env.local), scores the answers and writes evals/report.md.
 *
 *   pnpm eval                 all cases
 *   pnpm eval --only 08       cases whose file name contains "08"
 *   pnpm eval --min 0.85      exit with code 1 below 85% passed checks (for CI)
 *
 * Uses the same prompt, schema and settings as the app (streamOfferExtraction), so the numbers
 * describe what users get. Costs real tokens with a real provider (12 small calls).
 */
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { parseArgs } from "node:util";

import { loadEnvConfig } from "@next/env";
import { streamOfferExtraction } from "@/features/extract/server/stream-extraction";
import {
  type Check,
  type EvalCase,
  evalCasesSchema,
  scoreExtraction,
  summarize,
} from "@/lib/ai/evals/score-extraction";
import { getModel, modelLabel } from "@/lib/ai/model";

loadEnvConfig(process.cwd(), true);

const DIR = path.join(process.cwd(), "evals", "extract");
const REPORT = path.join(process.cwd(), "evals", "report.md");

type CaseResult = {
  file: string;
  why: string;
  checks: Check[];
  error?: string;
  ms: number;
  tokens: number;
};

async function runCase(model: ReturnType<typeof getModel>, c: EvalCase): Promise<CaseResult> {
  const offer = await readFile(path.join(DIR, c.file), "utf8");
  const started = performance.now();
  try {
    const result = streamOfferExtraction({ model, offer });
    const [output, usage] = await Promise.all([result.output, result.totalUsage]);
    return {
      file: c.file,
      why: c.why,
      checks: scoreExtraction(output, c.expected),
      ms: performance.now() - started,
      tokens: (usage.inputTokens ?? 0) + (usage.outputTokens ?? 0),
    };
  } catch (error) {
    return {
      file: c.file,
      why: c.why,
      checks: [],
      error: error instanceof Error ? error.message.split("\n")[0] : String(error),
      ms: performance.now() - started,
      tokens: 0,
    };
  }
}

const pct = (passed: number, total: number) =>
  total === 0 ? "-" : `${Math.round((passed / total) * 100)}%`;

function report(label: string, results: CaseResult[]): { markdown: string; score: number } {
  const stats = summarize(results.map((r) => r.checks));
  const passed = stats.reduce((sum, s) => sum + s.passed, 0);
  const total = stats.reduce((sum, s) => sum + s.total, 0);
  const errors = results.filter((r) => r.error).length;
  const tokens = results.reduce((sum, r) => sum + r.tokens, 0);
  const avgMs = results.reduce((sum, r) => sum + r.ms, 0) / Math.max(1, results.length);

  const lines = [
    "# Offer extraction evals",
    "",
    `Model: \`${label}\` · ${new Date().toISOString().slice(0, 10)} · ${results.length} cases · ` +
      `${errors} errors · ${tokens} tokens · ${(avgMs / 1000).toFixed(1)} s per case`,
    "",
    `**Overall: ${pct(passed, total)} of checks passed** (${passed}/${total}).`,
    "",
    "| Field | Passed |",
    "| --- | --- |",
    ...stats.map((s) => `| ${s.field} | ${pct(s.passed, s.total)} (${s.passed}/${s.total}) |`),
    "",
    "## Cases",
    "",
    "| Case | What it tests | Result |",
    "| --- | --- | --- |",
    ...results.map((r) => {
      const failed = r.checks.filter((c) => !c.pass);
      const result = r.error
        ? `error: ${r.error}`
        : failed.length === 0
          ? "ok"
          : failed.map((c) => `${c.field}: got ${c.got}, want ${c.want}`).join("<br>");
      return `| ${r.file.replace(/\.txt$/, "")} | ${r.why} | ${result.replace(/\|/g, "\\|")} |`;
    }),
    "",
    "Generated by `pnpm eval`. Cases and expected values: `evals/extract/`.",
    "",
  ];
  return { markdown: lines.join("\n"), score: total === 0 ? 0 : passed / total };
}

/** Run with a small pool: free tiers allow only a few requests per minute. */
async function mapWithLimit<T, R>(items: T[], limit: number, fn: (item: T) => Promise<R>) {
  const results: R[] = new Array<R>(items.length);
  let next = 0;
  await Promise.all(
    Array.from({ length: Math.min(limit, items.length) }, async () => {
      while (next < items.length) {
        const index = next++;
        const item = items[index];
        if (item !== undefined) results[index] = await fn(item);
      }
    }),
  );
  return results;
}

async function main() {
  const { values } = parseArgs({
    options: { only: { type: "string" }, min: { type: "string" } },
    allowPositionals: true, // pnpm may pass a literal "--" through
  });
  const cases = evalCasesSchema
    .parse(JSON.parse(await readFile(path.join(DIR, "cases.json"), "utf8")))
    .filter((c) => !values.only || c.file.includes(values.only));

  const model = getModel();
  const label = modelLabel(model);
  console.log(`Running ${cases.length} cases on ${label}...`);

  const results = await mapWithLimit(cases, 2, async (c) => {
    const r = await runCase(model, c);
    const failed = r.checks.filter((check) => !check.pass).map((check) => check.field);
    console.log(
      `${r.error ? "ERR " : failed.length ? "FAIL" : "ok  "} ${c.file}` +
        (r.error ? `  ${r.error}` : failed.length ? `  (${failed.join(", ")})` : ""),
    );
    return r;
  });

  const { markdown, score } = report(label, results);
  await writeFile(REPORT, markdown);
  console.log(`\n${markdown.split("\n")[4]}\nReport: evals/report.md`);

  const min = values.min ? Number(values.min) : undefined;
  if (min !== undefined && score < min) {
    console.error(`Below the required ${Math.round(min * 100)}%.`);
    process.exitCode = 1;
  }
}

main().catch((error: unknown) => {
  console.error(error);
  process.exitCode = 1;
});
